def search_news(query: str = "latest technology and AI news", category: Optional[str] = None) -> Dict[str, Any]:
    """Searches real-time news articles, breaking headlines, and editorial briefings across tech, business, science, world affairs, and local regions."""
    clean_query = (query or "").strip()
    q_lower = clean_query.lower()
    selected_cat = (category or "All").strip().title()

    # 1. Curated match: AI & Tech News
    if any(k in q_lower for k in ["tech", "ai", "artificial intelligence", "gemini", "deepmind", "agent", "gpu", "nvidia", "silicon", "chip", "software", "generative ui", "gen ui", "copilot"]):
        all_tech = AI_TECH_ARTICLES
        featured = all_tech[0]
        rest = all_tech[1:]
        return NewsSearchData(
            query=clean_query or "Technology & AI News",
            category="Technology & AI",
            total_results=len(all_tech),
            breaking_alert="BREAKING: Google DeepMind unveils unified Generative UI protocol and real-time autonomous agent SDK.",
            featured_article=featured,
            articles=rest,
            trending_topics=["#GenerativeUI", "#Gemini3", "#BlackwellUltra", "#AgenticAI", "#DeepMind"],
            suggested_followups=[
                "Explain the Google DeepMind Generative UI SDK architecture",
                "How does NVIDIA Blackwell Ultra affect AI inference costs?",
                "What are the W3C standards for AI agent interfaces?"
            ],
            last_updated="Just now"
        ).model_dump()

    # 2. Curated match: Business, Finance & Markets
    if any(k in q_lower for k in ["business", "market", "finance", "stocks", "wall street", "economy", "fed", "inflation", "revenue", "invest"]):
        all_biz = BUSINESS_MARKETS_ARTICLES
        featured = all_biz[0]
        rest = all_biz[1:]
        return NewsSearchData(
            query=clean_query or "Business & Financial Markets",
            category="Business & Markets",
            total_results=len(all_biz),
            breaking_alert="MARKETS: Global enterprise AI capital expenditure crosses $280 billion with accelerated automation adoption.",
            featured_article=featured,
            articles=rest,
            trending_topics=["#EnterpriseAI", "#FederalReserve", "#TechStocks", "#WallStreet", "#Productivity"],
            suggested_followups=[
                "Which sectors are seeing the fastest AI ROI?",
                "How does tech automation affect central bank interest rate decisions?",
                "Show recent venture capital funding for autonomous agents"
            ],
            last_updated="Just now"
        ).model_dump()

    # 3. Curated match: Science & Space Exploration
    if any(k in q_lower for k in ["space", "spacex", "starship", "nasa", "fusion", "quantum", "physics", "mars", "astronomy", "moon"]):
        all_sci = SCIENCE_SPACE_ARTICLES
        featured = all_sci[0]
        rest = all_sci[1:]
        return NewsSearchData(
            query=clean_query or "Science & Space Exploration",
            category="Science & Space",
            total_results=len(all_sci),
            breaking_alert="SPACE: SpaceX validates orbital propellant transfer and precision mechanical booster catch.",
            featured_article=featured,
            articles=rest,
            trending_topics=["#SpaceXStarship", "#NuclearFusion", "#Artemis", "#NASA", "#CleanEnergy"],
            suggested_followups=[
                "What is next for the NASA Artemis lunar landing timeline?",
                "How does AI control plasma confinement in nuclear fusion reactors?",
                "When is the next Starship orbital test flight scheduled?"
            ],
            last_updated="Just now"
        ).model_dump()

    # 4. Curated match: Bangladesh & Regional News
    if any(k in q_lower for k in ["bangladesh", "dhaka", "bd", "taka", "bkash"]):
        all_bd = BANGLADESH_ARTICLES
        featured = all_bd[0]
        rest = all_bd[1:]
        return NewsSearchData(
            query=clean_query or "Bangladesh Tech & Business News",
            category="Bangladesh",
            total_results=len(all_bd),
            breaking_alert="NATIONAL: Bangladesh tech and software export earnings surpass $2.4 billion milestone.",
            featured_article=featured,
            articles=rest,
            trending_topics=["#BangladeshTech", "#DhakaIT", "#DigitalBangladesh", "#BanglaQR", "#Fintech"],
            suggested_followups=[
                "What tax incentives exist for IT startups in Bangladesh?",
                "How is Bangla QR transforming retail micro-merchants?",
                "Show details on upcoming high-tech IT parks in Bangladesh"
            ],
            last_updated="Just now"
        ).model_dump()

    # 5. Dynamic synthesis via Gemini for any custom news topic (e.g., crypto, climate, electric vehicles, sports, geopolitics, etc.)
    dynamic_data = _generate_dynamic_news(clean_query, selected_cat)
    if dynamic_data and (dynamic_data.featured_article or dynamic_data.articles):
        return dynamic_data.model_dump()

    # 6. Default Fallback: Blend of top breaking tech and science news
    combined_articles = AI_TECH_ARTICLES + SCIENCE_SPACE_ARTICLES
    featured = combined_articles[0]
    rest = combined_articles[1:4]
    return NewsSearchData(
        query=clean_query or "Global Breaking Headlines",
        category="General News",
        total_results=len(combined_articles),
        breaking_alert="LATEST: Global technology and science developments lead international briefings.",
        featured_article=featured,
        articles=rest,
        trending_topics=["#GenerativeUI", "#DeepMind", "#SpaceX", "#BlackwellUltra", "#CleanEnergy"],
        suggested_followups=[
            "Show latest AI and machine learning news",
            "What are the top business headlines today?",
            "Show recent space exploration and scientific discoveries"
        ],
        last_updated="Just now"
    ).model_dump()

