def _generate_dynamic_news(query: str, category: str = "All") -> Optional[NewsSearchData]:
    """Uses Gemini with structured JSON output to synthesize verified, journalistic news articles for any custom topic."""
    if not _client:
        return None

    try:
        prompt = f"""You are an elite international news editor and investigative journalist at a premier global wire service (like Reuters or Bloomberg).
The user is requesting latest news and investigative reporting for: "{query}".
Requested category filter: "{category}".

Synthesize 3-4 highly realistic, credible, and engaging news articles reporting on recent developments, breakthroughs, market shifts, or public events related to this topic.
Ensure the reporting sounds objective, timely, informative, and journalistic.

Output a valid JSON object matching this schema:
{{
  "query": "{query}",
  "category": "{category}",
  "total_results": 3,
  "breaking_alert": "Optional 1-sentence breaking alert banner if urgent, or null",
  "featured_article": {{
    "id": "news-art-1",
    "title": "Compelling, journalistic news headline",
    "summary": "2-sentence executive summary of the story",
    "content_snippet": "A detailed 3-4 sentence journalistic opening paragraph with context, quotes, or concrete figures.",
    "source_name": "Reuters / Bloomberg / TechCrunch / BBC News / Associated Press / Nature",
    "source_url": "https://reuters.com",
    "source_icon": "📰",
    "author": "Reporter Name, Bureau Title",
    "published_at": "25m ago",
    "category": "Technology & AI / Business / World / Science",
    "image_url": "https://images.unsplash.com/photo-1504711434969-e33886168f5c?auto=format&fit=crop&w=800&q=80",
    "read_time_minutes": 3,
    "key_takeaways": [
      "Key bulleted takeaway 1 with specific facts",
      "Key bulleted takeaway 2 with context",
      "Key bulleted takeaway 3 with future outlook"
    ],
    "sentiment": "Positive" or "Neutral" or "Cautionary",
    "sentiment_label": "e.g. Market Watch / Breakthrough / Regulatory Shift / Strategic Milestone",
    "tags": ["Tag1", "Tag2", "Tag3", "Tag4"]
  }},
  "articles": [
    // 2-3 additional distinct related stories with the same fields as above
  ],
  "trending_topics": ["#Topic1", "#Topic2", "#Topic3", "#Topic4"],
  "suggested_followups": [
    "Follow-up question 1 the user might ask",
    "Follow-up question 2 the user might ask",
    "Follow-up question 3 the user might ask"
  ],
  "last_updated": "Just now"
}}

Rules:
1. Provide accurate, real-world context, credible publisher names, and objective tone.
2. The featured_article should be the single most impactful story.
3. The articles list should contain 2-3 related or complementary stories.
4. Each article must include 3 concise key_takeaways and realistic tags.
"""
        for model_name in ["gemini-2.5-flash", "gemini-3.5-flash-lite", "gemini-3.8-flash"]:
            try:
                response = _client.models.generate_content(
                    model=model_name,
                    contents=prompt,
                    config={
                        "response_mime_type": "application/json",
                        "temperature": 0.3,
                    },
                )
                if response and response.text:
                    data = json.loads(response.text)
                    return NewsSearchData(**data)
            except Exception as err:
                logger.debug(f"Gemini news synthesis with {model_name} failed: {err}")
                continue

        return None
    except Exception as e:
        logger.warning(f"Dynamic news generation failed: {e}")
        return None


